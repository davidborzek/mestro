//! The embedded web app's file table: every file under the dist
//! dir lands in the binary (build.rs generates TABLE from
//! $MESTRO_WEB_DIST / web/dist). Routing here is URL-shaped:
//! known paths serve their bytes, unknown non-file paths fall
//! back to index.html (the SPA's own router takes over), anything
//! that looks like a file 404s — a missing hashed asset must not
//! render the app shell with a JS content type.

/// one embedded file: URL path + bytes. Content type and cache
/// policy derive from the path ([`content_type`], [`cache_control`])
#[derive(Debug)]
pub(crate) struct Asset {
    pub path: &'static str,
    pub bytes: &'static [u8],
}

// generated by build.rs from the built dist dir
pub(super) static TABLE: &[Asset] = include!(concat!(env!("OUT_DIR"), "/mestro-remote-assets.rs"));

/// the entry a GET resolves to: exact match, `/` as index.html,
/// or None (the SPA fallback / 404 decision then sees [`looks_like_file`])
pub(crate) fn resolve<'a>(assets: &'a [Asset], path: &str) -> Option<&'a Asset> {
    let index = find(assets, "/index.html")?;
    match path {
        "/" | "" => Some(index),
        _ => find(assets, path),
    }
}

fn find<'a>(assets: &'a [Asset], path: &str) -> Option<&'a Asset> {
    assets.iter().find(|a| a.path == path)
}

/// an SPA route, not a file request: the last segment has no
/// extension. Unknown such paths get the app shell
pub(crate) fn looks_like_file(path: &str) -> bool {
    path.rsplit('/')
        .next()
        .is_some_and(|last| last.contains('.'))
}

/// a route the app shell answers: `/` (the index) or a non-file
/// path no asset matches. The AP-mode portal landing redirects
/// exactly these — assets keep serving (the setup page needs
/// them), unknown file-likes keep their 404
pub(crate) fn is_app_route(assets: &[Asset], path: &str) -> bool {
    path == "/" || (resolve(assets, path).is_none() && !looks_like_file(path))
}

/// the reply content type by file extension
pub(crate) fn content_type(path: &str) -> &'static str {
    match path.rsplit('.').next().unwrap_or_default() {
        "html" => "text/html; charset=utf-8",
        "js" | "mjs" => "text/javascript; charset=utf-8",
        "css" => "text/css; charset=utf-8",
        "json" => "application/json",
        "webmanifest" => "application/manifest+json",
        "png" => "image/png",
        "jpg" | "jpeg" => "image/jpeg",
        "svg" => "image/svg+xml",
        "ico" => "image/x-icon",
        "woff2" => "font/woff2",
        "txt" => "text/plain; charset=utf-8",
        _ => "application/octet-stream",
    }
}

/// the cache policy: hashed assets are immutable forever, icons
/// a day, the shell and the manifest must revalidate (a new
/// release must be picked up)
pub(crate) fn cache_control(path: &str) -> &'static str {
    if path.starts_with("/assets/") {
        "public, max-age=31536000, immutable"
    } else if path.starts_with("/icons/") {
        "public, max-age=86400"
    } else {
        "no-cache"
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // a runtime table, like the generated one but from a real dir
    // (leaked: test data, 'static by construction)
    fn table_of(dir: &std::path::Path) -> Vec<Asset> {
        let mut files = Vec::new();
        let mut stack = vec![dir.to_path_buf()];
        while let Some(dir) = stack.pop() {
            for entry in std::fs::read_dir(&dir).unwrap() {
                let path = entry.unwrap().path();
                if path.is_dir() {
                    stack.push(path);
                } else {
                    files.push(path);
                }
            }
        }
        files.sort();
        files
            .into_iter()
            .map(|file| {
                let url = format!("/{}", file.strip_prefix(dir).unwrap().to_string_lossy());
                Asset {
                    path: Box::leak(url.into_boxed_str()),
                    bytes: Box::leak(std::fs::read(&file).unwrap().into_boxed_slice()),
                }
            })
            .collect()
    }

    // a dist dir: index.html, manifest, a hashed asset, an icon —
    // one per test: parallel tests must not share the path
    fn fake_dist(tag: &str) -> std::path::PathBuf {
        let dir = std::env::temp_dir().join(format!("mestro-assets-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        for (rel, bytes) in [
            ("index.html", b"<html>mestro</html>".as_slice()),
            ("manifest.webmanifest", br#"{"name":"mestro"}"#),
            ("assets/app-abc123.js", b"console.log(1)"),
            ("icons/icon-192.png", b"\x89PNG-not-really"),
        ] {
            let file = dir.join(rel);
            std::fs::create_dir_all(file.parent().unwrap()).unwrap();
            std::fs::write(file, bytes).unwrap();
        }
        dir
    }

    #[test]
    fn the_compiled_table_has_an_index() {
        // works for both dist layouts: the pre-PWA single file and
        // the directory
        assert!(TABLE.iter().any(|a| a.path == "/index.html"));
    }

    #[test]
    fn root_serves_the_index() {
        let dir = fake_dist("root");
        let table = table_of(&dir);
        let index = resolve(&table, "/").unwrap();
        assert_eq!(index.path, "/index.html");
        assert_eq!(index.bytes, b"<html>mestro</html>");
        assert_eq!(content_type(index.path), "text/html; charset=utf-8");
        assert_eq!(cache_control(index.path), "no-cache");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn hashed_assets_carry_their_mime_and_immutable_cache() {
        let dir = fake_dist("mime");
        let table = table_of(&dir);
        let js = resolve(&table, "/assets/app-abc123.js").unwrap();
        assert_eq!(content_type(js.path), "text/javascript; charset=utf-8");
        assert_eq!(
            cache_control(js.path),
            "public, max-age=31536000, immutable"
        );
        let png = resolve(&table, "/icons/icon-192.png").unwrap();
        assert_eq!(content_type(png.path), "image/png");
        assert_eq!(cache_control(png.path), "public, max-age=86400");
        let manifest = resolve(&table, "/manifest.webmanifest").unwrap();
        assert_eq!(content_type(manifest.path), "application/manifest+json");
        assert_eq!(cache_control(manifest.path), "no-cache");
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn unknown_file_like_paths_are_not_found() {
        let dir = fake_dist("missing");
        let table = table_of(&dir);
        assert!(resolve(&table, "/assets/app-missing.js").is_none());
        assert!(resolve(&table, "/icons/icon-999.png").is_none());
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn spa_routes_vs_files() {
        assert!(looks_like_file("/assets/app.js"));
        assert!(looks_like_file("/icons/icon-192.png"));
        assert!(!looks_like_file("/"));
        assert!(!looks_like_file("/system"));
        assert!(!looks_like_file("/setup/player"));
    }

    #[test]
    fn app_routes_are_the_shell_paths_and_nothing_else() {
        let dir = fake_dist("routes");
        let table = table_of(&dir);
        // `/` and unknown non-file paths are app routes
        assert!(is_app_route(&table, "/"));
        assert!(is_app_route(&table, "/setup/wifi"));
        assert!(is_app_route(&table, "/settings/info"));
        // assets (known or not) and file-likes are not
        assert!(!is_app_route(&table, "/index.html"));
        assert!(!is_app_route(&table, "/assets/app-abc123.js"));
        assert!(!is_app_route(&table, "/assets/app-missing.js"));
        assert!(!is_app_route(&table, "/icons/icon-999.png"));
        let _ = std::fs::remove_dir_all(&dir);
    }
}
