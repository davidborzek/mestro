//! What the clock shows before the time can be trusted. The Pi has no
//! RTC: until NTP answers, the clock reads whatever the last saved
//! time was (or 1970), and a wrong time on a clock is worse than
//! none. "Trustworthy" is deliberately simple and needs no NTP
//! coupling: the year is at least the year this binary was built.

use chrono::{Datelike as _, NaiveDateTime, Timelike as _};

// `pub const BUILD_YEAR: i32 = <year>;` (build.rs)
include!(concat!(env!("OUT_DIR"), "/build_year.rs"));

/// the topbar and standby text while the time is not trustworthy
pub const PLACEHOLDER: &str = "--:--";

/// is a clock showing this year plausibly right
pub fn is_trustworthy(year: i32, build_year: i32) -> bool {
    year >= build_year
}

/// the hub's greeting word and date line for one instant: nothing
/// but the player name while the time is not trustworthy (a
/// "Good night" over a 1970 date would contradict the placeholder)
pub fn hub_lines(now: NaiveDateTime, build_year: i32, player: &str) -> (String, String) {
    if !is_trustworthy(now.year(), build_year) {
        return (String::new(), player.to_string());
    }
    let greeting = match now.hour() {
        5..=11 => "Good morning",
        12..=17 => "Good afternoon",
        18..=22 => "Good evening",
        _ => "Good night",
    };
    let date = now.format("%A, %d. %B").to_string().to_uppercase();
    (greeting.to_string(), format!("{date} · {player}"))
}

/// the clock values every face receives for one instant
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ClockValues {
    /// false = show the placeholder, hands and digits stay hidden
    pub valid: bool,
    pub hour: i32,
    pub minute: i32,
    pub time_label: String,
    pub date_label: String,
}

impl ClockValues {
    /// the values for `now`; an untrusted time yields the placeholder
    /// label, no date and zeroed digits (custom skins get the same)
    pub fn at(now: NaiveDateTime) -> Self {
        Self::at_with(now, BUILD_YEAR)
    }

    pub fn at_with(now: NaiveDateTime, build_year: i32) -> Self {
        if is_trustworthy(now.year(), build_year) {
            Self {
                valid: true,
                hour: now.hour() as i32,
                minute: now.minute() as i32,
                time_label: now.format("%H:%M").to_string(),
                date_label: now.format("%a %d %b").to_string().to_uppercase(),
            }
        } else {
            Self {
                valid: false,
                hour: 0,
                minute: 0,
                time_label: PLACEHOLDER.to_string(),
                date_label: String::new(),
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use chrono::NaiveDate;

    fn at(year: i32, month: u32, day: u32, hour: u32, minute: u32) -> NaiveDateTime {
        NaiveDate::from_ymd_opt(year, month, day)
            .unwrap()
            .and_hms_opt(hour, minute, 0)
            .unwrap()
    }

    #[test]
    fn the_build_year_itself_and_later_are_trusted() {
        assert!(is_trustworthy(2026, 2026));
        assert!(is_trustworthy(2027, 2026));
        assert!(!is_trustworthy(2025, 2026));
        assert!(!is_trustworthy(1970, 2026));
    }

    #[test]
    fn the_build_year_is_the_year_of_the_build() {
        // generated by build.rs: not a stale or zero constant
        const { assert!(BUILD_YEAR >= 2025) };
        assert!(
            BUILD_YEAR <= chrono::Local::now().year(),
            "built in the future: {BUILD_YEAR}"
        );
    }

    #[test]
    fn a_trusted_time_shows_digits_and_the_date() {
        let values = ClockValues::at_with(at(2026, 11, 21, 7, 5), 2026);
        assert_eq!(
            values,
            ClockValues {
                valid: true,
                hour: 7,
                minute: 5,
                time_label: "07:05".into(),
                date_label: "SAT 21 NOV".into(),
            }
        );
    }

    #[test]
    fn the_epoch_before_ntp_shows_the_placeholder() {
        let values = ClockValues::at_with(at(1970, 1, 1, 0, 0), 2026);
        assert_eq!(
            values,
            ClockValues {
                valid: false,
                hour: 0,
                minute: 0,
                time_label: "--:--".into(),
                date_label: String::new(),
            }
        );
    }

    #[test]
    fn a_time_that_jumps_forward_flips_to_digits_on_the_next_tick() {
        // NTP sets the clock: the very next values are real ones
        let before = ClockValues::at_with(at(1970, 1, 1, 0, 3), 2026);
        let after = ClockValues::at_with(at(2026, 11, 21, 14, 30), 2026);
        assert!(!before.valid && after.valid);
        assert_eq!(after.time_label, "14:30");
    }

    #[test]
    fn the_hub_greets_by_the_hour_only_with_a_trusted_time() {
        let morning = hub_lines(at(2026, 11, 21, 7, 0), 2026, "Wohnzimmer");
        assert_eq!(
            morning,
            (
                "Good morning".to_string(),
                "SATURDAY, 21. NOVEMBER · Wohnzimmer".to_string()
            )
        );
        for (hour, word) in [
            (12, "Good afternoon"),
            (18, "Good evening"),
            (23, "Good night"),
            (3, "Good night"),
        ] {
            assert_eq!(hub_lines(at(2026, 11, 21, hour, 0), 2026, "p").0, word);
        }
        // before NTP: no greeting, no date, just the player
        assert_eq!(
            hub_lines(at(1970, 1, 1, 0, 0), 2026, "Wohnzimmer"),
            (String::new(), "Wohnzimmer".to_string())
        );
    }

    #[test]
    fn the_real_clock_of_this_build_is_trusted() {
        assert!(ClockValues::at(chrono::Local::now().naive_local()).valid);
    }
}
